// Turf.js-д зориулсан GeoJSON Feature хэлбэрт хөрвүүлэх
export function districtToGeoJSON(d: DistrictFeature) {
  return {
    type: "Feature" as const,
    properties: { name: d.name },
    geometry: {
      type: "Polygon" as const,
      coordinates: [[...d.coords, d.coords[0]]],
    },
  };
}
